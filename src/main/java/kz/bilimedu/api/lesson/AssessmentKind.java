package kz.bilimedu.api.lesson;

/**
 * Тип оценочной единицы. В версии 2023 года это был булев markSochSor,
 * который не различал обычный урок от суммативной работы вовсе.
 */
public enum AssessmentKind {

    /** Обычный урок без суммативной оценки. */
    LESSON,

    /** Суммативное оценивание за раздел. */
    SOR,

    /** Суммативное оценивание за четверть: не более одного на четверть (правило D5). */
    SOCH
}
